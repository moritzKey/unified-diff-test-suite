package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	bluekeyes "github.com/bluekeyes/go-gitdiff/gitdiff"
	gitleaks "github.com/gitleaks/go-gitdiff/gitdiff"
)

// go-gitdiff and the fork that the secret scanner gitleaks uses have the same API.
// The conversion is written twice only because the types are distinct.

func mode(m os.FileMode) any {
	if m == 0 {
		return nil
	}
	return fmt.Sprintf("%06o", uint32(m))
}

// An empty name is go-gitdiff's way of saying "no file on this side".
func emptyIsNone(name string) any {
	if name == "" {
		return nil
	}
	return jb(name)
}

func gitdiffStatus(isNew, isDelete, isRename, isCopy bool) string {
	switch {
	case isNew:
		return "added"
	case isDelete:
		return "deleted"
	case isRename:
		return "renamed"
	case isCopy:
		return "copied"
	}
	return "modified"
}

var gitdiffOps = map[int]string{0: "context", 1: "delete", 2: "add"}

func init() {
	common := func(name, pkg, homepage, notes string) M {
		return M{
			"name": name, "package": pkg, "homepage": homepage,
			"api":       "gitdiff.Parse(reader)",
			"pathStyle": "stripped",
			"statuses":  []string{"added", "deleted", "renamed", "copied"},
			"noNewline": "line",
			// Parse returns the text in front of the first file as a preamble: commit and mail headers are expected.
			"scope": []string{"git", "git-wrapped"},
			"notes": notes,
		}
	}
	adapters["go-gitdiff"] = adapter{
		meta: common("go-gitdiff", "github.com/bluekeyes/go-gitdiff", "https://github.com/bluekeyes/go-gitdiff",
			`README: "A Go library for parsing and applying patches generated by git diff, git show, and git format-patch."`),
		parse: func(data []byte) ([]M, error) {
			files, _, err := bluekeyes.Parse(bytes.NewReader(data))
			if err != nil {
				return nil, err
			}
			out := []M{}
			for _, f := range files {
				hunks := []M{}
				var added, deleted int64
				for _, t := range f.TextFragments {
					lines := []M{}
					for _, l := range t.Lines {
						lines = append(lines, M{"type": gitdiffOps[int(l.Op)], "text": jb(strings.TrimSuffix(l.Line, "\n")), "no_newline": l.NoEOL()})
					}
					added += t.LinesAdded
					deleted += t.LinesDeleted
					hunks = append(hunks, M{"old_start": t.OldPosition, "old_lines": t.OldLines, "new_start": t.NewPosition, "new_lines": t.NewLines, "section": jb(t.Comment), "lines": lines})
				}
				m := M{
					"old_path": emptyIsNone(f.OldName), "new_path": emptyIsNone(f.NewName),
					"status":   gitdiffStatus(f.IsNew, f.IsDelete, f.IsRename, f.IsCopy),
					"old_mode": mode(f.OldMode), "new_mode": mode(f.NewMode),
					"binary": f.IsBinary, "hunks": hunks,
				}
				if f.IsRename || f.IsCopy {
					m["similarity"] = f.Score
				}
				if !f.IsBinary {
					m["additions"], m["deletions"] = added, deleted
				}
				out = append(out, m)
			}
			return out, nil
		},
	}
	adapters["gitleaks-go-gitdiff"] = adapter{
		meta: func() M {
			m := common("go-gitdiff (gitleaks fork)", "github.com/gitleaks/go-gitdiff", "https://github.com/gitleaks/go-gitdiff",
				"The fork of go-gitdiff that the secret scanner gitleaks reads `git log -p` with. It delivers files through a channel.")
			m["api"] = "gitdiff.Parse(reader), reading the channel to its end"
			return m
		}(),
		parse: func(data []byte) ([]M, error) {
			// The fork streams files through a channel. An error in the middle of the input is not
			// reported to the caller: the channel is closed and the remaining files are never seen.
			files, err := gitleaks.Parse(bytes.NewReader(data))
			if err != nil {
				return nil, err
			}
			out := []M{}
			for f := range files {
				hunks := []M{}
				var added, deleted int64
				for _, t := range f.TextFragments {
					lines := []M{}
					for _, l := range t.Lines {
						lines = append(lines, M{"type": gitdiffOps[int(l.Op)], "text": jb(strings.TrimSuffix(l.Line, "\n")), "no_newline": l.NoEOL()})
					}
					added += t.LinesAdded
					deleted += t.LinesDeleted
					hunks = append(hunks, M{"old_start": t.OldPosition, "old_lines": t.OldLines, "new_start": t.NewPosition, "new_lines": t.NewLines, "section": jb(t.Comment), "lines": lines})
				}
				m := M{
					"old_path": emptyIsNone(f.OldName), "new_path": emptyIsNone(f.NewName),
					"status":   gitdiffStatus(f.IsNew, f.IsDelete, f.IsRename, f.IsCopy),
					"old_mode": mode(f.OldMode), "new_mode": mode(f.NewMode),
					"binary": f.IsBinary, "hunks": hunks,
				}
				if f.IsRename || f.IsCopy {
					m["similarity"] = f.Score
				}
				if !f.IsBinary {
					m["additions"], m["deletions"] = added, deleted
				}
				out = append(out, m)
			}
			return out, nil
		},
	}
}
