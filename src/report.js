#!/usr/bin/env node
// Turn results/*.json (written by src/run.js) into RESULTS.md, and
// results/apply/*.json (written by src/apply.js) into APPLY.md.
//
//   node src/report.js
//
// The reports are statements of fact about specific versions on specific
// inputs. They are generated; edit this file, not the reports.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, loadRegistry } from './adapters.js';
import { buildApplyReport } from './apply-report.js';
import { loadIndex } from './corpus.js';

const TIERS = ['git', 'git-wrapped', 'git-config', 'combined', 'gnu'];
const TIER_LABEL = {
  git: '`git diff`',
  'git-wrapped': 'wrapped (`show`, `log -p`, `format-patch`)',
  'git-config': 'other naming (`--no-prefix`, …)',
  combined: 'merges',
  gnu: 'GNU `diff -u`',
};
// The traps, in the order of SPEC.md.
const TRAPS = [
  ['fake-file-header', 'content that looks like `--- `/`+++ ` headers'],
  ['zero-count', 'zero-length ranges (`-5,0`, `+0,0`)'],
  ['no-newline', '`\\ No newline at end of file`'],
  ['line-splitting', 'CR, FF, U+2028 inside a line'],
  ['cr', 'carriage returns in content'],
  ['space-in-path', 'spaces in file names'],
  ['quoted-path', 'quoted file names (non-ASCII, quotes, control characters)'],
  ['header-ambiguity', 'names that only the `diff --git` line carries'],
  ['rename', 'renames'],
  ['copy', 'copies'],
  ['mode', 'mode changes'],
  ['empty-file', 'empty files'],
  ['binary', 'binary files'],
  ['symlink', 'symbolic links'],
  ['submodule', 'submodules'],
];

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => `\`${String(s).replace(/`/g, "'")}\``;

function load() {
  const index = loadIndex();
  const byId = new Map(index.vectors.map((v) => [v.id, v]));
  const adapters = [];
  for (const spec of loadRegistry()) {
    const file = join(ROOT, 'results', `${spec.name}.json`);
    if (!existsSync(file)) continue;
    adapters.push({ spec, ...JSON.parse(readFileSync(file, 'utf8')) });
  }
  return { index, byId, adapters };
}

function tally(results, pred) {
  const t = { pass: 0, total: 0, crash: 0, hang: 0, inScope: false, na: 0 };
  for (const [id, r] of Object.entries(results)) {
    if (!pred(id, r)) continue;
    if (r.verdict === 'n/a') {
      t.na++;
      continue;
    }
    t.total++;
    if (r.verdict === 'pass') t.pass++;
    if (r.verdict === 'crash') t.crash++;
    if (r.verdict === 'hang') t.hang++;
    if (r.inScope) t.inScope = true;
  }
  return t;
}

function cell(t) {
  if (t.total === 0) return '–';
  const extra = [t.crash ? `${t.crash} exception${t.crash > 1 ? 's' : ''}` : '', t.hang ? `${t.hang} hang${t.hang > 1 ? 's' : ''}` : ''].filter(Boolean).join(', ');
  const body = `${t.pass}/${t.total}${extra ? ` (${extra})` : ''}`;
  return t.inScope ? (t.pass === t.total ? `**${body}**` : body) : `<sub>${body}</sub>`;
}

const versionOf = (meta) => (meta.engine ? `${meta.engine.replace(/^libgit2 /, '')} (via ${meta.package} ${meta.version})` : meta.version ?? '');

export function buildReport() {
  const { index, byId, adapters } = load();
  const out = [];
  const push = (...l) => out.push(...l);
  const refs = adapters.filter((a) => a.spec.reference);
  const libs = adapters.filter((a) => !a.spec.reference);

  push('# Results', '');
  push('<!-- Generated by `node src/report.js` from results/*.json. Do not edit. -->', '');
  push(
    `${index.count} vectors, produced by git ${index.tools.git} and GNU diffutils ${index.tools.diffutils}. Every number below is "vectors on which the parser's answer agreed with the verified expectation / vectors it was given".`,
    '',
    '**Read this first.**',
    '',
    '- This is not a ranking. The corpus is a collection of hard cases, most of them rare; a low number says "there are inputs this parser does not handle", not "this parser is bad". Several of the libraries were written for one narrow job and do it well.',
    '- Only values a library actually returns are compared. A parser that does not report file modes is never marked down for file modes. See [`adapters/PROTOCOL.md`](adapters/PROTOCOL.md).',
    '- Small print (<sub>like this</sub>) marks a tier that the library does not set out to handle, as far as its documentation says. Those numbers are information, not findings.',
    '- A vector that cannot be given to a library at all (bytes that are not valid UTF-8 for a text API, several files for a one-file parser) is left out of its totals.',
    '- The versions are the latest releases at the time of the run. Findings may be fixed by the time you read this; [`FINDINGS.md`](FINDINGS.md) records what was already known upstream.',
    '',
  );

  push('## Summary', '');
  push(`| parser | version | ${TIERS.map((t) => TIER_LABEL[t]).join(' | ')} |`);
  push(`| --- | --- | ${TIERS.map(() => '---').join(' | ')} |`);
  for (const a of [...libs, ...refs]) {
    const cells = TIERS.map((t) => cell(tally(a.results, (id) => byId.get(id)?.tier === t)));
    push(`| ${a.spec.reference ? `_${esc(a.meta.name)}_` : `[${esc(a.meta.name)}](#${a.spec.name.toLowerCase()})`} | ${esc(versionOf(a.meta))} | ${cells.join(' | ')} |`);
  }
  push('', 'The two reference parsers are part of this repository (`src/refparse.js`, `reference/python/udiff_reference.py`). They are in the table to show that every vector can be parsed from its text alone, without being told how it was produced.', '');

  push('## By kind of trap', '');
  push('Vectors of the `git` tier only, grouped by tag. A vector can carry several tags.', '');
  push(`| trap | vectors | ${libs.map((a) => esc(a.meta.name)).join(' | ')} |`);
  push(`| --- | --- | ${libs.map(() => '---').join(' | ')} |`);
  for (const [tag, label] of TRAPS) {
    const ids = index.vectors.filter((v) => v.tier === 'git' && v.tags.includes(tag)).map((v) => v.id);
    if (ids.length === 0) continue;
    const set = new Set(ids);
    const cells = libs.map((a) => {
      const t = tally(a.results, (id) => set.has(id));
      if (t.total === 0) return '–';
      return t.pass === t.total ? `**${t.pass}/${t.total}**` : `${t.pass}/${t.total}`;
    });
    push(`| ${label} | ${ids.length} | ${cells.join(' | ')} |`);
  }
  push('');

  push('## Per parser', '');
  for (const a of libs) {
    const m = a.meta;
    push(`### ${a.spec.name}`, '');
    push(`${esc(m.name)} ${esc(versionOf(m))} · ${m.language} · <${m.homepage}>`, '');
    push(`- Under test: ${code(m.api)}${a.meta.flavor ? ` on output re-produced with \`--${a.meta.flavor}\`, the form this library asks git for` : ''}`);
    push(`- Declared scope: ${(m.scope ?? []).map(code).join(', ')}${m.singleFile ? ' — one file per call' : ''}`);
    if (m.notes) push(`- ${m.notes}`);
    push('');
    const inScope = Object.entries(a.results).filter(([, r]) => r.inScope && r.verdict !== 'n/a');
    const failed = inScope.filter(([, r]) => r.verdict !== 'pass');
    if (failed.length === 0) {
      push(`All ${inScope.length} vectors in scope agree.`, '');
    } else {
      const byKind = new Map();
      for (const [id, r] of failed) {
        const kinds = new Set(r.findings.map((f) => f.kind));
        for (const kind of kinds) {
          const e = byKind.get(kind) ?? { ids: [], sample: null };
          e.ids.push(id);
          e.sample ??= { id, message: r.findings.find((f) => f.kind === kind).message };
          byKind.set(kind, e);
        }
      }
      push(`${inScope.length - failed.length} of ${inScope.length} vectors in scope agree. The ${failed.length} others, by kind of difference (a vector can show several):`, '');
      push('| difference | vectors | example |', '| --- | --- | --- |');
      for (const [kind, e] of [...byKind].sort((x, y) => y[1].ids.length - x[1].ids.length)) {
        const label = kind === 'crash' ? 'exception' : kind;
        push(`| ${label} | ${e.ids.length} | ${code(e.sample.id)}: ${esc(e.sample.message).slice(0, 220)} |`);
      }
      push('');
      push('<details><summary>Vectors</summary>', '');
      push(failed.map(([id]) => code(id)).join(', '), '', '</details>', '');
    }
    const outside = Object.entries(a.results).filter(([, r]) => !r.inScope && r.verdict !== 'n/a');
    if (outside.length) {
      const parts = TIERS.map((t) => {
        const tt = tally(Object.fromEntries(outside), (id) => byId.get(id)?.tier === t);
        return tt.total ? `${t} ${tt.pass}/${tt.total}` : null;
      }).filter(Boolean);
      push(`Outside the declared scope (for information): ${parts.join(', ')}.`, '');
    }
    const na = Object.values(a.results).filter((r) => r.verdict === 'n/a').length;
    if (na) push(`Not applicable: ${na} vectors.`, '');
  }

  push('## Reproducing', '');
  push('```', 'cd adapters/node && npm ci', 'cd ../python && python3 -m venv .venv && .venv/bin/pip install -r requirements.txt', 'cd ../.. && node src/run.js && node src/report.js', '```', '');
  push('`node src/try.js <adapter> <vector-id> --raw` shows what one parser returned for one vector.', '');
  return `${out.join('\n')}`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = buildReport();
  writeFileSync(join(ROOT, 'RESULTS.md'), text);
  console.log(`RESULTS.md written (${text.split('\n').length} lines)`);
  const apply = buildApplyReport();
  if (apply !== null) {
    writeFileSync(join(ROOT, 'APPLY.md'), apply);
    console.log(`APPLY.md written (${apply.split('\n').length} lines)`);
  }
}
