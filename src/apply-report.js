// Turn results/apply/*.json (written by src/apply.js) into APPLY.md.
// Called by src/report.js; the text is generated, edit this file instead.

import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadRegistry } from './adapters.js';
import { loadIndex } from './corpus.js';

const TIERS = ['git', 'git-wrapped', 'git-config', 'gnu'];
const TIER_LABEL = { git: '`git diff`', 'git-wrapped': 'wrapped', 'git-config': 'other naming', gnu: 'GNU `diff -u`' };
// The traps, in the order of SPEC.md (as in RESULTS.md).
const TRAPS = [
  ['fake-file-header', 'content that looks like `--- `/`+++ ` headers'],
  ['zero-count', 'zero-length ranges (`-5,0`, `+0,0`)'],
  ['no-newline', '`\\ No newline at end of file`'],
  ['line-splitting', 'CR, FF, U+2028 inside a line'],
  ['cr', 'carriage returns in content'],
  ['space-in-path', 'spaces in file names'],
  ['quoted-path', 'quoted file names (non-ASCII, quotes, control characters)'],
  ['header-ambiguity', 'names that only the `diff --git` line carries'],
  ['rename', 'renames'],
  ['copy', 'copies'],
  ['mode', 'mode changes'],
  ['empty-file', 'empty files'],
  ['binary', 'binary patches'],
  ['symlink', 'symbolic links'],
];
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => `\`${String(s).replace(/`/g, "'")}\``;
const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;

function load() {
  const out = [];
  for (const spec of loadRegistry(undefined, 'appliers')) {
    const file = join(ROOT, 'results', 'apply', `${spec.name}.json`);
    if (existsSync(file)) out.push({ spec, ...JSON.parse(readFileSync(file, 'utf8')) });
  }
  return out;
}

function count(results, verdict, tier) {
  return Object.entries(results).filter(([id, r]) => r.verdict === verdict && (!tier || id.split('/')[0] === tier)).length;
}
const tested = (results, tier) => Object.entries(results).filter(([id, r]) => r.verdict !== 'n/a' && (!tier || id.split('/')[0] === tier)).length;

/** The same complaint about different files, lines or numbers is one complaint. */
function gist(message) {
  return String(message)
    .replace(/^"(?:[^"\\]|\\.)*": /, '') // the file a one-file library was working on
    .replace(/\S*udts-apply-\S*/g, 'FILE')
    .replace(/(?<![A-Za-z])'[^']*'/g, 'FILE') // 'f.txt', but not the apostrophe of "can't"
    .replace(/"(?:[^"\\]|\\.)*"/g, 'FILE')
    .replace(/\b[\w-]+(?:\.[\w-]+)*\.[A-Za-z]{1,5}\b/g, 'FILE')
    .replace(/\d+/g, 'N')
    .replace(/\s*\|.*$/, '')
    .slice(0, 120);
}

const versionOf = (m) => (m.library_version ? `${m.library_version} (via ${m.package} ${m.version})` : m.version ?? '');

/** APPLY.md, or null when no applier has been run. */
export function buildApplyReport() {
  const appliers = load();
  if (appliers.length === 0) return null;
  const index = loadIndex();
  const refs = appliers.filter((a) => a.spec.reference);
  const tools = appliers.filter((a) => !a.spec.reference);
  const patches = Math.max(...appliers.map((a) => tested(a.results)));
  const out = [];
  const push = (...l) => out.push(...l);

  push('# Applying the patches', '');
  push('<!-- Generated by `node src/report.js` from results/apply/*.json. Do not edit. -->', '');
  push(
    `Of the ${index.count} vectors, ${patches} are patches in the plain sense: the vector records the file tree before and the file tree after, and the diff is what git or GNU diff printed for the two. For each of them the old tree is written to an empty directory, the program under test applies the diff there, and the directory is read back and compared with the new tree, byte for byte, file modes and symbolic links included. A library that patches one file at a time is given each file section together with the old content of that file.`,
    '',
    'There are four ways this can end:',
    '',
    '| | the program said | and the files are |',
    '| --- | --- | --- |',
    '| **right** | done | exactly the new tree |',
    '| **refused** | error | untouched |',
    '| **left half-done** | error | changed, and not the new tree |',
    '| **wrong** | done | not the new tree |',
    '',
    '**Read this first.**',
    '',
    '- "Refused" is a limitation: the caller is told, and nothing is lost. "Wrong" is the column that matters — a file with different content, a file that should be gone, a file that is gone and should not be, and no error to say so.',
    '- This is not a ranking. The corpus collects hard cases; every one of these programs applies an ordinary patch correctly.',
    '- Every diff here is unmodified output of git or GNU diff, applied to exactly the tree it was made from. Nothing is fuzzy, offset or already applied.',
    '- The invocation is in the table. Other options give other results; `git apply --unidiff-zero` is listed next to `git apply` to show one such case.',
    '- The versions are the ones installed where this was run. What was already known to each project is in [`FINDINGS.md`](FINDINGS.md).',
    '',
  );

  push('## Summary', '');
  push('| program | version | how it is called | patches | right | refused | left half-done | **wrong** | exception |');
  push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const a of [...tools, ...refs]) {
    const r = a.results;
    const n = (v) => count(r, v) || '–';
    const wrong = count(r, 'wrong');
    push(
      `| ${a.spec.reference ? `_${esc(a.meta.name)}_` : `[${esc(a.meta.name)}](#${a.spec.name.toLowerCase()})`} | ${esc(versionOf(a.meta))} | ${code(a.meta.api)} | ${tested(r)} | ${count(r, 'ok')} | ${n('refused')} | ${n('partial')} | ${wrong ? `**${wrong}**` : '–'} | ${count(r, 'crash') + count(r, 'hang') || '–'} |`,
    );
  }
  push('', 'What the wrong results are (a patch can show several):', '');
  push('| program | wrong | content of a file | a file that should be gone | a file that is missing | file or symbolic link | executable bit |');
  push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const a of tools) {
    const wrong = Object.values(a.results).filter((r) => r.verdict === 'wrong');
    if (wrong.length === 0) continue;
    const having = (kind) => wrong.filter((r) => r.findings.some((f) => f.kind === kind)).length || '–';
    push(`| ${esc(a.meta.name)} | ${wrong.length} | ${having('content')} | ${having('extra')} | ${having('missing')} | ${having('type')} | ${having('mode')} |`);
  }
  push(
    '',
    'The reference appliers are part of this repository (`src/refapply.js`, `reference/python/udiff_reference.py`). They are in the table to show that every one of these patches can be applied from its text and the old files alone. A library that patches one file at a time is not given the vectors in which no file content changes (pure renames, mode changes), a library that takes text is not given files that are not valid UTF-8, libgit2 is not given what GNU diff wrote, and patch-package, pnpm, Yarn and Bun, which always remove `a/` and `b/` and take no `-p`, are given only the vectors of the `git` and `git-config` tiers whose names carry those two prefixes. Bun, whose packages never hold a symbolic link, is also not given an old tree that has one. That is why the number of patches differs.',
    '',
  );

  push('## By tier', '');
  push(`| program | ${TIERS.map((t) => TIER_LABEL[t]).join(' | ')} |`, `| --- | ${TIERS.map(() => '---').join(' | ')} |`);
  for (const a of tools) {
    const cells = TIERS.map((t) => {
      const total = tested(a.results, t);
      if (!total) return '–';
      const wrong = count(a.results, 'wrong', t);
      return `${count(a.results, 'ok', t)}/${total}${wrong ? `, **${wrong} wrong**` : ''}`;
    });
    push(`| ${esc(a.meta.name)} | ${cells.join(' | ')} |`);
  }
  push('');

  push('## By kind of trap', '');
  push('Vectors of the `git` tier, grouped by tag; a vector can carry several. "12/14, **1**" reads: 14 patches given, 12 applied correctly, 1 applied wrongly without an error.', '');
  push(`| trap | ${tools.map((a) => esc(a.meta.name)).join(' | ')} |`, `| --- | ${tools.map(() => '---').join(' | ')} |`);
  for (const [tag, label] of TRAPS) {
    const ids = new Set(index.vectors.filter((v) => v.tier === 'git' && v.tags.includes(tag)).map((v) => v.id));
    const cells = tools.map((a) => {
      const mine = Object.entries(a.results).filter(([id, r]) => ids.has(id) && r.verdict !== 'n/a');
      if (mine.length === 0) return '–';
      const ok = mine.filter(([, r]) => r.verdict === 'ok').length;
      const wrong = mine.filter(([, r]) => r.verdict === 'wrong').length;
      return `${ok === mine.length ? `**${ok}/${mine.length}**` : `${ok}/${mine.length}`}${wrong ? `, **${wrong}**` : ''}`;
    });
    if (cells.every((c) => c === '–')) continue;
    push(`| ${label} | ${cells.join(' | ')} |`);
  }
  push('');

  push('## Per program', '');
  for (const a of tools) {
    const m = a.meta;
    push(`### ${a.spec.name}`, '');
    push(`${esc(m.name)} ${esc(versionOf(m))} · ${m.language} · <${m.homepage}>`, '');
    push(`- Under test: ${code(m.api)} — ${m.applies === 'tree' ? 'on a directory' : 'one file at a time'}`);
    if (m.eofNewline === false) push('- It returns a list of lines; whether the last line ends with a newline is not part of its answer and is not compared.');
    if (m.notes) push(`- ${m.notes}`);
    push('');
    const entries = Object.entries(a.results).filter(([, r]) => r.verdict !== 'n/a');
    const by = (v) => entries.filter(([, r]) => r.verdict === v);
    const ok = by('ok').length;
    if (ok === entries.length) {
      push(`All ${entries.length} patches are applied correctly.`, '');
      continue;
    }
    push(`${ok} of ${entries.length} patches are applied correctly.`, '');
    const wrong = by('wrong');
    if (wrong.length) {
      push(`**Wrong without an error (${wrong.length}):**`, '', '| vector | what is in the directory afterwards |', '| --- | --- |');
      for (const [id, r] of wrong) {
        const first = r.findings[0];
        push(`| ${code(id)} | ${esc(first.message).slice(0, 230)}${r.findings.length > 1 ? ` (and ${plural(r.findings.length - 1, 'more difference')})` : ''} |`);
      }
      push('');
    }
    for (const [verdict, title] of [['partial', 'Left half-done'], ['refused', 'Refused'], ['crash', 'Exception'], ['hang', 'No answer']]) {
      const list = by(verdict);
      if (!list.length) continue;
      const groups = new Map();
      for (const [id, r] of list) {
        const key = gist(r.findings[0]?.message ?? '');
        const g = groups.get(key) ?? { ids: [], sample: r.findings[0]?.message ?? '' };
        g.ids.push(id);
        groups.set(key, g);
      }
      push(`**${title} (${list.length}):**`, '', '| what it said | vectors | for example |', '| --- | --- | --- |');
      for (const g of [...groups.values()].sort((x, y) => y.ids.length - x.ids.length)) {
        push(`| ${esc(gist(g.sample))} | ${g.ids.length} | ${code(g.ids[0])} |`);
      }
      push('');
    }
  }

  push('## Reproducing', '');
  push('```', 'node src/apply.js                         # every applier; writes results/apply/*.json', 'node src/apply.js --adapter gnu-patch --show', 'node src/report.js                        # this file', '```', '');
  return out.join('\n');
}
